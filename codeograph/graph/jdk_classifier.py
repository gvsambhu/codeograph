"""
JdkClassifier — says whether a class name is a JDK class.

The JDK is the public top-level types of the packages that the system modules
of a JDK export without qualification: the JDK the committed list names (the
newest the project uses, at least as new as any it supports). The list is
generated by ``scripts/ListJdkTypes.java`` and committed as ``jdk_types.json``,
so the answer depends on that file and not on the JDK installed where the tool
runs.
"""

from __future__ import annotations

import json
from collections.abc import Collection, Iterable, Mapping
from functools import cache
from importlib import resources


class JdkClassifier:
    """
    Decides *JDK* for a name in one of two forms:

      - a qualified name (``java.util.Map``, ``java.util.Map.Entry``,
        ``javax.sql.DataSource``) is a JDK class if its package is a listed
        package;
      - a name with no package (``String``, ``Map.Entry``) is a JDK class if its
        first segment is a listed type of ``java.lang``, or of a package the
        file imports on demand.

    Whether a name belongs to the corpus is not this class's question: the
    caller asks it only about names no corpus class claimed.
    """

    def __init__(self, packages: Mapping[str, Collection[str]]) -> None:
        """:param packages: package name → the public top-level types it exports."""
        self._types = {package: frozenset(names) for package, names in packages.items()}

    @classmethod
    def committed(cls) -> JdkClassifier:
        """The classifier for the committed JDK list."""
        return _committed()

    def is_jdk(self, name: str, wildcard_packages: Iterable[str] = ()) -> bool:
        """
        :param name:              a name as the resolver returns it.
        :param wildcard_packages: packages the naming file imports on demand.
        """
        segments = name.split(".")
        first_type = next((i for i, segment in enumerate(segments) if segment[:1].isupper()), None)
        if first_type is None:
            return False
        if first_type > 0:
            return ".".join(segments[:first_type]) in self._types
        outer = segments[0]
        return any(outer in self._types.get(package, ()) for package in ("java.lang", *wildcard_packages))


@cache
def _committed() -> JdkClassifier:
    text = resources.files("codeograph.graph").joinpath("jdk_types.json").read_text(encoding="utf-8")
    return JdkClassifier(json.loads(text)["packages"])
